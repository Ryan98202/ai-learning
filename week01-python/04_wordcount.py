# ============================================================
# 先认识两个新容器
# ============================================================
# 列表（list）：一串有顺序的值，用方括号
#   numbers = [3, 1, 4]
#   fruits = ["苹果", "梨"]

# 字典（dict）：一堆"名字 → 值"的配对，用花括号
#   freq = {"苹果": 3, "梨": 1}
#
# 字典这次要用到的就三条：
#   freq["苹果"]          取出"苹果"对应的值
#   freq["苹果"] = 5      把"苹果"对应的值改成 5
#   "苹果" in freq        判断"苹果"在不在字典里，返回 True 或 False

# ============================================================
# 函数：把一段代码打包起来，起个名字
# ============================================================
# def 是英文 define（定义）的缩写。
# 括号里的 s 叫"参数" —— 调用这个函数时要交进去的输入。
# return 是"交出去的结果"。
#
# 下面这个函数的签名（第一行）已经写好了，你不用改。


def count_chars(s):
    """统计字符串 s 里每个字出现的次数，返回一个字典。

    这三行引号包起来的东西叫 docstring，是这个函数的说明书。
    写不写不影响运行，但好习惯从现在就养。
    """
    result = {}      # 先准备一个空字典来装结果

    # --------------------------------------------------------
    # TODO：遍历 s 里的每一个字，把次数记进 result
    #
    # 遍历用 for，写法：
    #   for ch in s:
    #       （缩进的代码块）
    # 读作："把 s 里的东西一个一个拿出来，每次叫它 ch，执行下面这些事。"
    # ch 这个名字是我起的，你可以改成别的（比如 zi、c），但要改就全改。
    #
    # 循环体里只有一件事，但要分两种情况：
    #   情况一：ch 已经在 result 里了  → 把它对应的次数加 1
    #            写法：result[ch] = result[ch] + 1
    #   情况二：ch 还不在 result 里     → 让它从 1 开始
    #            写法：result[ch] = 1
    #
    # 怎么区分这两种情况？用你刚学会的 if：
    #   if ch in result:
    #       ...
    #   else:
    #       ...
    for ch in s:
        if ch in result:
            result[ch] = result[ch] + 1
        else:
            result[ch] = 1
    return result


# ============================================================
# 下面是"使用"这个函数 —— 这部分已经写好了，不用改
# ============================================================

freq = count_chars("学")

# len() 是"长度"，对字典来说就是"里面有多少对"
print(f"这句话共有 {len(freq)} 个不同的字。")
