# 这一节把 02 的"只猜一次"改成"可以一直猜，直到猜对"，
# 并且统计玩家一共猜了几次。
#
# while 的意思：只要条件成立，就反复执行下面缩进的代码块。
#   条件一旦不成立，就往下走，不再重复。

secret = 7

# 这个变量用来数玩家猜了几次。每猜一次，加 1。
tries = 0

# ------------------------------------------------------------
# 思路（先读懂，再动手）：
#
#   1) 先给 guess 一个初始值，它只要不等于 secret，循环就能进去
#   2) 只要 guess 不等于 secret，就一直问下去
#   3) 每问一次，tries 加 1
#   4) 猜对之后循环自动结束，再告诉他用了多少次
#
# 三个符号别搞混：
#   =    赋值，"把右边存进左边"
#   ==   判断是否相等（两个等号）
#   !=   判断是否不相等
#
# while 的写法：
#   while guess != secret:
#       （缩进的代码块，会反复执行）
#   读作："只要 guess 不等于 secret，就做下面这些事"
# ------------------------------------------------------------

guess = 0       # 初始值。它只要不等于 secret，循环就能进去

# ------------------------------------------------------------
# TODO：把下面的 while 循环写出来
#
# 循环体里要做三件事（都要缩进，且顺序有讲究）：
#   一、用 input 问一次，把结果转成数字，存进 guess
#        写法：guess = int(input("再猜一个 1 到 10 的数字："))
#   二、tries 加 1
#        写法：tries = tries + 1
#   三、打印 "太大了" 或 "太小了"（这里需要用到 if / elif，就是你刚学会的）
#
# 顺序很重要：必须先问、再计数、最后判断提示。
# 如果写成先判断后问，判断用的还是上一轮的值，逻辑就错了。
#
# ⚠️ 如果跑起来提示一直刷、怎么都停不下来：
#    说明循环体里少了"重新给 guess 赋值"，条件永远成立。
#    按 Ctrl + C 强制停止，然后回来检查那三件事是不是都写了。
# ------------------------------------------------------------


# 下面这行在循环外面（没有缩进），所以循环结束之后才执行
print(f"猜对了！你一共猜了 {tries} 次。")

