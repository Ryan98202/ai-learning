# 把固定的 7 换成每次都不一样的随机数，需要改两处 ——
#   1) 在文件最上面加一行：  import random
#   2) 把 secret = 7 换成：  secret = random.randint(1, 10)
#
# random.randint(1, 10) 的意思是"随机给我一个 1 到 10 之间的整数"。
# 注意它包含 1 和 10 本身，和数学里的区间写法不太一样。
# ------------------------------------------------------------
import random      
guess = int(input("猜一个 1 到 10 的数字："))
secret = random.randint(1, 10)

if guess > secret:
    print("太大了")
elif guess < secret:
    print("太小了")
else:
    print("猜对了！")   