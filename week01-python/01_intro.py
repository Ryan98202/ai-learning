# ============================================================
# 第一部分：变量是什么
# ============================================================
# 变量就是"给一个值起个名字"。
# 等号 = 不是数学里的"相等"，它的意思是"把右边的东西存进左边的名字里"。
# 所以下面这行的读法是：把"长沙"这个值，存进 city 这个名字里。

city = "长沙"

# 存进去之后，用这个名字就等于用它代表的值
print(city)

# ============================================================
# 第二部分：三种最基本的类型
# ============================================================

# 类型 1：字符串（str）—— 一段文字，用引号包起来
# 单引号和双引号都行，效果一样，但要成对
greeting = "你好"
greeting2 = '你好'          # 和上面等价

# 类型 2：整数（int）—— 没有小数点的数字，不用引号
year = 2026

# 类型 3：浮点数（float）—— 有小数点的数字
rate = 0.75

# type() 能告诉你一个值是什么类型，不确定的时候可以用它查
print(type(greeting))       # <class 'str'>
print(type(year))           # <class 'int'>
print(type(rate))           # <class 'float'>

# 最容易踩的坑：有引号和没引号是两回事
print("2026")               # 这是文字
print(2026)                 # 这是数字
# 上面两行打印出来长得一模一样，但本质不同。看下面这组对比：
print("2026" + "1")         # 文字 + 文字 = 拼起来  → 20261
print(2026 + 1)             # 数字 + 数字 = 算数    → 2027

# ============================================================
# 第三部分：f-string（往文字里塞变量）
# ============================================================
# 在引号前面加一个小写 f，就可以在花括号里直接放变量名。
# 这是 Python 里最常用的拼接方式，一定要记住。

print(f"我在{city}，今年是{year}年")

# 不加 f 会怎样？花括号会被当成普通文字原样打印
print("我在{city}，今年是{year}年")

